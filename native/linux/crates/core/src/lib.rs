    #[test]
    fn aes_gcm_roundtrip_and_html_extract() {
        let mut state = GuideState::default();
        state.region = "us_in".to_string();
        state
            .f
            .insert("q_first".to_string(), "Priya (+1-555-0102)".to_string());
        let mut acct = HashMap::new();
        acct.insert("inst".to_string(), "Chase".to_string());
        acct.insert("own".to_string(), "Joint".to_string());
        acct.insert("last4".to_string(), "4412".to_string());
        state.lists.insert("accounts".to_string(), vec![acct]);

        let pkg = encrypt_state(&state, "amber-cedar-lantern-orbit-river")
            .expect("encrypt succeeds");
        assert_eq!(pkg.app, "family-field-guide");
        assert_eq!(pkg.v, 1);

        let pkg_json = serde_json::to_string(&pkg).unwrap();
        let html = format!(
            "<!doctype html><html><body><script id=\"ffg-pkg\" type=\"application/json\">{pkg_json}</script></body></html>"
        );
        let extracted = parse_backup_payload(&html).expect("HTML extraction succeeds");
        let restored =
            decrypt_state(&extracted, "amber-cedar-lantern-orbit-river").expect("decrypt succeeds");
        assert_eq!(restored.region, "us_in");
        assert_eq!(
            restored.f.get("q_first").map(String::as_str),
            Some("Priya (+1-555-0102)")
        );
        assert!(decrypt_state(&extracted, "wrong-passphrase").is_err());
    }

    #[test]
    fn shamir_2of3_matches_web_js_interop_vector() {
        // Real vector generated by root app.js sssSplit2of3("amber-cedar-lantern-orbit-river")
        let c1 = "FFG-1-39F9-5E0D-03F8-66D0-86D0-D9C2-0FA9-4188-E876-6689-C6CF-BF9E-BAB4-368E-BEAC-AF";
        let c2 = "FFG-2-D15E-1AB5-909C-6914-BB18-3FE8-AAEA-3097-647A-7E7E-2613-C39C-F304-FABC-FDEC-D3";
        let c3 = "FFG-3-89CA-26DD-E149-6CA1-59A9-9407-C922-1F6B-E97E-76DA-8FAE-1E6B-3D9D-BE5B-3525-0E";
        let expected = "amber-cedar-lantern-orbit-river";

        assert_eq!(sss_combine_2of3(c1, c2).unwrap(), expected);
        assert_eq!(sss_combine_2of3(c1, c3).unwrap(), expected);
        assert_eq!(sss_combine_2of3(c2, c3).unwrap(), expected);

        let fresh = sss_split_2of3(expected).unwrap();
        assert_eq!(sss_combine_2of3(&fresh[0], &fresh[1]).unwrap(), expected);
        assert_eq!(sss_combine_2of3(&fresh[1], &fresh[2]).unwrap(), expected);
        assert!(sss_combine_2of3(&fresh[0], &fresh[0]).is_err());
    }

