@testable import FamilyGuideCore
import XCTest

@MainActor
final class FamilyGuideCoreTests: XCTestCase {
    private func makeTempDir() throws -> URL {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("ffg-test-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    func testSchemaAndRegionsDecodeCleanly() throws {
        let url = GuideStore.locateGuideDataURL()
        XCTAssertNotNil(url)
        let store = try GuideStore(storageDirectory: makeTempDir())
        XCTAssertEqual(store.data.TABS.count, 6)
        XCTAssertEqual(store.data.PLAYBOOK.count, 7)
        XCTAssertEqual(store.data.MONEY_GUIDE.count, 6)
        XCTAssertEqual(store.data.PRO_FINDER.count, 5)
        XCTAssertEqual(store.data.REGIONS.count, 9)
        XCTAssertEqual(store.data.DICE_WORDS.count, 2048)
        XCTAssertNotNil(store.data.REGIONS["us_in"]?.moneyGuide)
        XCTAssertNotNil(store.data.REGIONS["in"]?.proFinder)
    }

    func testAesGcmEncryptDecryptAndHtmlExtraction() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.f["q_first"] = "Priya Sharma · 206-555-0148"
        store.state.lists["crypto"] = [["platform": "Ledger", "access": "Safe drawer", "helper": "Arjun"]]
        let pw = "amber-cedar-lantern-orbit-river"

        let pkg = try CryptoEngine.encrypt(state: store.state, passphrase: pw)
        let decrypted = try CryptoEngine.decrypt(package: pkg, passphrase: pw)
        XCTAssertEqual(decrypted.f["q_first"], "Priya Sharma · 206-555-0148")
        XCTAssertEqual(decrypted.lists["crypto"]?.first?["platform"], "Ledger")

        XCTAssertThrowsError(try CryptoEngine.decrypt(package: pkg, passphrase: "wrong-passphrase"))

        let jsonStr = String(decoding: try JSONEncoder().encode(pkg), as: UTF8.self)
        let fakeHtml = "<!DOCTYPE html><html><body><script id=\"ffg-pkg\" type=\"application/json\">\(jsonStr)</script></body></html>"
        let parsed = try CryptoEngine.parseBackupPayload(from: fakeHtml)
        let fromHtml = try CryptoEngine.decrypt(package: parsed, passphrase: pw)
        XCTAssertEqual(fromHtml.f["q_first"], "Priya Sharma · 206-555-0148")
    }

    func testCrossPlatformShamir2of3InteropWithWebJs() throws {
        // Real vector generated by app.js sssSplit2of3("amber-cedar-lantern-orbit-river")
        let s1 = "FFG-1-39F9-5E0D-03F8-66D0-86D0-D9C2-0FA9-4188-E876-6689-C6CF-BF9E-BAB4-368E-BEAC-AF"
        let s2 = "FFG-2-D15E-1AB5-909C-6914-BB18-3FE8-AAEA-3097-647A-7E7E-2613-C39C-F304-FABC-FDEC-D3"
        let s3 = "FFG-3-89CA-26DD-E149-6CA1-59A9-9407-C922-1F6B-E97E-76DA-8FAE-1E6B-3D9D-BE5B-3525-0E"

        XCTAssertEqual(try CryptoEngine.sssCombine2of3(s1, s2), "amber-cedar-lantern-orbit-river")
        XCTAssertEqual(try CryptoEngine.sssCombine2of3(s2, s3), "amber-cedar-lantern-orbit-river")
        XCTAssertEqual(try CryptoEngine.sssCombine2of3(s1, s3), "amber-cedar-lantern-orbit-river")

        // Swift round-trip
        let swiftShares = try CryptoEngine.sssSplit2of3(secret: "banyan-copper-falcon-glacier-anchor")
        XCTAssertEqual(swiftShares.count, 3)
        XCTAssertEqual(try CryptoEngine.sssCombine2of3(swiftShares[0], swiftShares[2]), "banyan-copper-falcon-glacier-anchor")
    }

    func testReadinessAuditsDetectCryptoSeedsAndFullIds() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.lists["crypto"] = [["platform": "Ledger", "access": "alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima", "helper": ""]]
        store.state.lists["gov_ids"] = [["who": "Me", "idtype": "SSN", "last4": "123-45-6789", "where": "Safe"]]

        var audit = store.computeAudit()
        XCTAssertEqual(audit.first(where: { $0.id == "crypto_safety" })?.sev, .high)
        XCTAssertEqual(audit.first(where: { $0.id == "gov_id_privacy" })?.sev, .high)

        store.state.lists["crypto"] = [["platform": "Ledger", "access": "Metal backup in safe", "helper": "Arjun"]]
        store.state.lists["gov_ids"] = [["who": "Me", "idtype": "SSN", "last4": "4812", "where": "Safe"]]
        audit = store.computeAudit()
        XCTAssertEqual(audit.first(where: { $0.id == "crypto_safety" })?.sev, .ok)
        XCTAssertEqual(audit.first(where: { $0.id == "gov_id_privacy" })?.sev, .ok)
    }

    func testSearchSmartMergeAndDemo() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.region = "us_in"
        store.loadDemo()
        XCTAssertTrue(store.state.isDemo)
        XCTAssertFalse(store.search("$1M").isEmpty)
        XCTAssertFalse(store.search("AILA").isEmpty)

        store.state.region = "in"
        store.normalize()
        XCTAssertFalse(store.search("NALSA").isEmpty)

        var inc = GuideState()
        inc.f["d_charity"] = "St. Jude"
        let plan = store.computeMergePlan(incoming: inc)
        XCTAssertEqual(plan.newFields, 1)
        store.applyMerge(incoming: inc, overwriteConflicts: false)
        XCTAssertEqual(store.state.f["d_charity"], "St. Jude")
    }

    func testCustomSectionTemplateAndDelete() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        XCTAssertEqual(store.data.SECTION_TEMPLATES.count, 8)
        let tpl = store.data.SECTION_TEMPLATES[0]
        store.applySectionTemplate(tpl)
        XCTAssertEqual(store.state.customTabs.count, 1)
        let tid = store.state.customTabs[0].id
        XCTAssertEqual(store.state.tab, tid)
        XCTAssertFalse((store.state.extra[tid] ?? []).isEmpty)

        store.deleteCustomSection(tid)
        XCTAssertTrue(store.state.customTabs.isEmpty)
        XCTAssertEqual(store.state.tab, "start")
    }

    func testExportsAndRegionLocalization() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.region = "in"
        store.normalize()
        store.state.f["h_triage"] = "Apollo Oncology 24/7"
        store.state.f["h_redflag"] = "Fever >= 100.4F -> ER"
        store.state.f["q_first"] = "Meera (+91-98765-43210)"

        let er = store.exportErGrabSheetText()
        XCTAssertTrue(er.contains("Apollo Oncology 24/7"))
        XCTAssertTrue(er.contains("Fever >= 100.4F"))
        XCTAssertTrue(er.contains("112"))

        let summary = store.exportExecutiveSummaryText()
        XCTAssertTrue(summary.contains("Meera (+91-98765-43210)"))
        XCTAssertTrue(summary.contains("ER / Active Illness Alert"))
    }

    func testAccessibilityAndReadModeStateRoundTrip() throws {
        let dir = try makeTempDir()
        let store = try GuideStore(storageDirectory: dir)
        store.state.readMode = true
        store.state.largeText = true
        store.state.highContrast = true
        store.save(touch: false)

        let reloaded = try GuideStore(storageDirectory: dir)
        XCTAssertTrue(reloaded.state.readMode)
        XCTAssertTrue(reloaded.state.largeText)
        XCTAssertTrue(reloaded.state.highContrast)
    }

    func testPassphraseDefaultSixWordsAndCorruptStatePreserved() throws {
        let dir = try makeTempDir()
        let store = try GuideStore(storageDirectory: dir)
        let pw = CryptoEngine.generatePassphrase(words: store.data.DICE_WORDS)
        XCTAssertEqual(pw.split(separator: "-").count, 6)

        let stateURL = dir.appendingPathComponent("state.json")
        try Data("{corrupt json".utf8).write(to: stateURL)
        let recovered = try GuideStore(storageDirectory: dir)
        XCTAssertEqual(recovered.state.tab, "start")
        let corruptBackupURL = dir.appendingPathComponent("state.json.corrupt")
        XCTAssertTrue(FileManager.default.fileExists(atPath: corruptBackupURL.path))
    }

    func testApplyMergePhotosFireDrillAndTimestamps() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.fireDrill = ["fd1": true, "fd2": false]
        store.state.lastDryRun = "2025-01-01T00:00:00Z"
        store.state.reviewed = "2025-03-01T00:00:00Z"
        store.state.photos = [
            PhotoSnippet(id: "p0", label: "Existing", dataUrl: "data:image/png;base64,AAAA")
        ]

        var inc = GuideState()
        inc.fireDrill = ["fd1": false, "fd2": true, "fd3": true]
        inc.lastDryRun = "2025-02-01T00:00:00Z"
        inc.reviewed = "2025-02-01T00:00:00Z"
        inc.photos = [
            PhotoSnippet(id: "bad", label: "XSS", dataUrl: "javascript:alert(1)"),
            PhotoSnippet(id: "dup", label: "Existing", dataUrl: "data:image/png;base64,AAAA")
        ]
        for i in 1...12 {
            inc.photos.append(PhotoSnippet(id: "p\(i)", label: "Doc \(i)", dataUrl: "data:image/jpeg;base64,BBBB\(i)"))
        }

        let summary = store.applyMerge(incoming: inc, overwriteConflicts: false)
        XCTAssertTrue(summary.contains("+9 photos"))
        XCTAssertEqual(store.state.photos.count, 10)
        XCTAssertFalse(store.state.photos.contains(where: { $0.dataUrl.hasPrefix("javascript:") }))
        XCTAssertEqual(store.state.fireDrill["fd1"], true)
        XCTAssertEqual(store.state.fireDrill["fd2"], true)
        XCTAssertEqual(store.state.fireDrill["fd3"], true)
        XCTAssertEqual(store.state.lastDryRun, "2025-02-01T00:00:00Z")
        XCTAssertEqual(store.state.reviewed, "2025-03-01T00:00:00Z")
    }

    func testFullStatePrivacyAuditWithoutLetterFalsePositives() throws {
        let store = try GuideStore(storageDirectory: makeTempDir())
        store.state.f["letter"] = "I love you very much every single day and hope this keeps everyone safe always"
        var audit = store.computeAudit()
        XCTAssertNil(audit.first(where: { $0.id == "crypto_safety" }))
        XCTAssertNil(audit.first(where: { $0.id == "gov_id_privacy" }))

        store.state.f["d_pm"] = "Vault PIN and SSN 123-45-6789"
        store.state.f["d_2fa"] = "alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima"
        audit = store.computeAudit()
        XCTAssertEqual(audit.first(where: { $0.id == "gov_id_privacy" })?.sev, .high)
        XCTAssertEqual(audit.first(where: { $0.id == "crypto_safety" })?.sev, .high)

        store.state.f["d_pm"] = "1Password emergency kit in fireproof safe"
        store.state.f["d_2fa"] = "Hardware YubiKey in safe"
        store.state.lists["gov_ids"] = [["who": "Me", "idtype": "SSN", "last4": "123456789", "where": "Safe"]]
        audit = store.computeAudit()
        XCTAssertEqual(audit.first(where: { $0.id == "gov_id_privacy" })?.sev, .high)
        XCTAssertNil(audit.first(where: { $0.id == "crypto_safety" }))
    }
}
